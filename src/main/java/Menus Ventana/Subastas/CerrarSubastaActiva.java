    //muestra en la ventana los datos de la subasta activa (o un aviso si no hay ninguna)
    private void actualizarInfoSubasta(){
        if (MenuPrincipal.subastaActiva == null){
            InfoSubasta.setText("No hay ninguna subasta activa en este momento.");
            return;
        }
        Obra o = MenuPrincipal.subastaActiva.getObra();
        Oferta mejor = MenuPrincipal.subastaActiva.getMejorOferta();
        String texto = "Obra: " + o.getTitulo() + " | Precio inicial: $" + MenuPrincipal.subastaActiva.getPrecioInicial();
        if (mejor == null){
            texto = texto + " | Sin ofertas";
        }
        else{
            texto = texto + " | Mejor oferta: $" + mejor.getOferta() + " (RUT: " + mejor.getRut() + ")";
        }
        InfoSubasta.setText(texto);
    }

