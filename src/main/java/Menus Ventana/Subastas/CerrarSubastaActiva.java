    private void CerrarSubastaBotonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CerrarSubastaBotonActionPerformed
        //verificar que haya una subasta activa
        if (MenuPrincipal.subastaActiva == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay ninguna subasta activa para cerrar.", "Error",javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // se guarda la obra antes de cerrar, para poder liberarla si es que no hubo ofertas
        Obra obraSubastada = MenuPrincipal.subastaActiva.getObra();

        boolean exito = MenuPrincipal.subastaActiva.cerrarSubasta(clientes);

        if (exito) { //Si se logró cerrar la subasta con éxito (con al menos una oferta registrada)
            subastas.add(MenuPrincipal.subastaActiva); //se añade la subasta al ArrayList de subastas cerradas
            String rutGanador = (MenuPrincipal.subastaActiva.getCliente()).getRut();
            int precioFinal = MenuPrincipal.subastaActiva.getPrecio();
            javax.swing.JOptionPane.showMessageDialog(this, "Subasta cerrada exitosamente. Ganador RUT: " + rutGanador + " por $" + precioFinal, "ÉXITO!",javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
        else {
            // si no hubo ofertas, la obra vuelve a estar disponible
            if (obraSubastada != null && obraSubastada.getEstado().equalsIgnoreCase("SUBASTANDO")) {
                obraSubastada.setEstado("Disponible");
            }
            javax.swing.JOptionPane.showMessageDialog(this, "La subasta se cerró sin ninguna oferta. La obra '" + obraSubastada.getTitulo() + "' vuelve a estar DISPONIBLE.", "Aviso",javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
        // Reiniciamos la variable de subastaActiva
        MenuPrincipal.subastaActiva = null;
        actualizarInfoSubasta();
    }//GEN-LAST:event_CerrarSubastaBotonActionPerformed

