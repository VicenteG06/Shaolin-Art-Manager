    private void buscarIDButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarIDButtonActionPerformed
        // TODO add your handling code here:
        String id = IDExposicion.getText().trim();
        if (id.isEmpty()){  
            JOptionPane.showMessageDialog(this, "Debe ingresar el ID de la Exposición.");
            return;
        }
        if (!exposiciones.containsKey(id)){ //si la exposicion no está en el mapa, se retorna y no se muestra nada
            JOptionPane.showMessageDialog(this, "La exposición no se encuentra en el sistema");
            exposicionActual = null;
            return;
        }
        //se guarda la exposición encontrada y se muestran sus datos actuales en los campos
        exposicionActual = exposiciones.get(id);
        tituloNuevo.setText(exposicionActual.getTitulo());
        fechaInicioNueva.setText(exposicionActual.getfechaInicio().toString());
        fechaTerminoNueva.setText(exposicionActual.getfechaTermino().toString());
        
    }//GEN-LAST:event_buscarIDButtonActionPerformed

