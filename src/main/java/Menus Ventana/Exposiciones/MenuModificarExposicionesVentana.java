    private void guardarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarButtonActionPerformed
        // TODO add your handling code here:
        
        if(exposicionActual == null){
            JOptionPane.showMessageDialog(this, "Primero debe buscar una Exposición por su ID.");
            return;
        }

        //se valida que el título no esté vacío
        String nuevoTitulo = tituloNuevo.getText().trim();
        if(nuevoTitulo.isEmpty()){
            JOptionPane.showMessageDialog(this, "El título no puede estar vacío.");
            return;
        }

        //se valida el formato de las fechas ingresadas
        LocalDate nuevaInicio;
        LocalDate nuevaTermino;
        try{
            nuevaInicio = LocalDate.parse(fechaInicioNueva.getText().trim());
            nuevaTermino = LocalDate.parse(fechaTerminoNueva.getText().trim());
        } catch (DateTimeParseException ex){
            JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use AAAA-MM-DD.");
            return;
        }

        //se validan ambas fechas juntas y se aplican los cambios
        if(!exposicionActual.cambiarFechas(nuevaInicio, nuevaTermino)){
            JOptionPane.showMessageDialog(this, "La exposición debe empezar antes de su término y durar como máximo un año.");
            return;
        }
        exposicionActual.cambiarTitulo(nuevoTitulo);

        JOptionPane.showMessageDialog(this, "La exposición fue modificada con éxito.");
    }//GEN-LAST:event_guardarButtonActionPerformed

