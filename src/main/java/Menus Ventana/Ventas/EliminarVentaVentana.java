    private void EliminarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarVentaActionPerformed
        //si no hay ventas, se da un aviso y se retorna al menu
        if (ventas.size() == 0){ 
            javax.swing.JOptionPane.showMessageDialog(this, "No existe esa Obra", "Error",javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        //se busca la obra vendida. De no existir, se da un aviso y se retorna al menu
        String id = IngreseIDObra.getText();
        if(!obras.containsKey(id)){
            javax.swing.JOptionPane.showMessageDialog(this, "No existe esa Obra", "Error",javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        Obra o = obras.get(id.toLowerCase());
        if(!(o.getEstado()).equals("VENDIDA")){
            javax.swing.JOptionPane.showMessageDialog(this, "La obra NO ha sido vendida", "Error",javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        //como se sabe que esta vendida, se busca, se elimina y se da un aviso de ello
        Venta auxV; 
        for (int i = 0 ; i < ventas.size() ; i++ ){
            auxV = (Venta) ventas.get(i);
            if (auxV.getObra() == o){
                Cliente cl = auxV.getCliente(); //se obtiene el cliente de la venta 
                if (!cl.elimObComprada(o)){ //se elimina la obra de la lista de obras compradas del cliente 
                    javax.swing.JOptionPane.showMessageDialog(this, "El cliente no es dueño de la Obra", "Error",javax.swing.JOptionPane.ERROR_MESSAGE);
                } 
                ventas.remove(auxV); //se elimina la venta de la lista de ventas 
                javax.swing.JOptionPane.showMessageDialog(this, "Venta eliminada con éxito", "EXITO!",javax.swing.JOptionPane.INFORMATION_MESSAGE);
                o.setEstado("Disponible");
                return;
            }
        }
        javax.swing.JOptionPane.showMessageDialog(this, "No se encontró la venta", "Error",javax.swing.JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_EliminarVentaActionPerformed

